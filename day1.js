// value is fixed and cannot be reassigned

// ====== NAMING VARIABLES ======
/*
    - only letters, numbers, underscores, and dollar signs
    - the first character cannot be a number
    - case sensitive
    - naming scheme can include camelCase, PascalCase, snake_case, and kebab-case
      camelCase is the most common variable naming in JS
*/

// ====== DATA TYPES ======
/*
    - string, number, boolean, null, and undefined (primitive)
    - object and array (non-primitive)

    - string -> "" or '' or ``
    - number -> 1, 2, 3, 4.5, -1
    - boolean -> true or false
    - null -> no value
    - undefined -> variable has been declared but not assigned a value
*/